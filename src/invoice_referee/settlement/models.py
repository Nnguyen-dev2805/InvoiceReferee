# Forward references across contract modules (Report.claim_comparisons ->
# B7ClaimComparison; the B7 present/decision views -> ReviewPayload /
# MoneyComponents / B7DecisionTarget) are resolved here, after every module is
# imported, so the split stays acyclic at import time. The namespace merges the
# globals of every contract module so lazy annotations (``date``, typing names,
# sibling contracts) all resolve.
from invoice_referee.settlement.contracts import (  # noqa: E402
    advance as _advance,
    base as _base,
    case as _case,
    fingerprint as _fingerprint,
    report as _report,
    run as _run,
    settlement as _settlement,
)
from invoice_referee.settlement.contracts import b3_contracts as _b3_contracts  # noqa: E402


def _rebuild_contracts() -> None:
    """Resolve every contract model's forward refs with a merged namespace.

    Kept in a function so the namespace/module/loop temporaries do not leak
    into this module's public namespace.
    """
    namespace: dict[str, object] = {}
    for module in (_base, _b3_contracts, _advance, _run, _report, _settlement,
                   _case, _fingerprint):
        namespace.update(vars(module))
    for obj in tuple(namespace.values()):
        if (isinstance(obj, type) and issubclass(obj, BaseModel)
                and obj is not BaseModel
                and str(getattr(obj, "__module__", "")).startswith(
                    "invoice_referee.settlement.contracts")):
            obj.model_rebuild(_types_namespace=namespace)


_rebuild_contracts()
del (
    _rebuild_contracts, _advance, _base, _b3_contracts, _case, _fingerprint,
    _report, _run, _settlement,
)
